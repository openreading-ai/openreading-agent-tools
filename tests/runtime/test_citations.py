class CitationCommandTests(unittest.TestCase):
    def test_cli_reads_through_verified_runtime_and_sanitizes_failure(self):
        import contextlib
        import io
        import tempfile
        from pathlib import Path
        from types import SimpleNamespace as Box
        from unittest.mock import patch

        from measurement import citations

        capture, review, retained = fixture()
        calls = []

        class Session:
            async def __aenter__(self):
                return self

            async def __aexit__(self, *args):
                pass

            async def initialize(self):
                pass

            async def call_tool(self, name, args):
                calls.append((name, args))
                return Box(
                    model_dump=lambda **kw: dict(
                        isError=False, content=[dict(type="text", text=json.dumps(retained))]
                    )
                )

        @contextlib.asynccontextmanager
        async def channel(params):
            self.assertEqual(params.command, str(root / "runtime/openreading-worker"))
            self.assertIn(str(root / "grant ü spaces"), params.args)
            yield None, None

        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp).resolve()
            (root / "capture.json").write_text(json.dumps(capture))
            (root / "review.json").write_text(json.dumps(review))
            argv = [
                "--capture",
                str(root / "capture.json"),
                "--review",
                str(root / "review.json"),
                "--runtime",
                str(root / "runtime"),
                "--input-root",
                str(root / "grant ü spaces"),
                "--client",
                "codex",
            ]
            with (
                patch.object(
                    citations,
                    "verify_release",
                    return_value=dict(
                        format_version="2", core_commit="c" * 40, worker_sha256="d" * 64
                    ),
                ),
                patch.object(citations, "stdio_client", channel),
                patch.object(citations, "ClientSession", return_value=Session()),
                contextlib.redirect_stdout(io.StringIO()) as output,
            ):
                self.assertEqual(citations.main(argv), 0)
            self.assertEqual(json.loads(output.getvalue())["verified_citations"], 1)
            self.assertEqual(
                calls, [("openreading_read", {"artifact_id": ARTIFACT, "evidence_ids": [EVIDENCE]})]
            )
            with (
                patch.object(citations, "verify_release", return_value=dict(format_version="1")),
                contextlib.redirect_stdout(io.StringIO()) as output,
            ):
                self.assertEqual(citations.main(argv), 1)
            self.assertEqual(json.loads(output.getvalue())["citation_evidence"], "refused")
            with (
                patch.object(
                    citations, "verify_release", side_effect=ValueError("PRIVATE DOCUMENT PASSWORD")
                ),
                contextlib.redirect_stdout(io.StringIO()) as output,
            ):
                self.assertEqual(citations.main(argv), 1)
            self.assertNotIn("PRIVATE", output.getvalue())
